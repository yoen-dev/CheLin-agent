# backend/config.py
"""
配置中心。
------------------------------------------------------------
所有"可调参数"（LLM 用哪个模型、限流窗口多长、连续几次异常触发转人工）
都集中写在这里，不要散落在业务代码里——
这样面试/答辩时被问"如果把 60 秒改成 30 秒会怎样"，
你只需要说"改这一个文件的一个数字"，而不是去代码里到处找魔法数字。

所有值都可以用环境变量覆盖，方便本地测试用不同参数跑并发/限流场景，
不需要改代码、不需要重新部署。
"""

import os
from dotenv import load_dotenv

# 从项目根目录的 .env 文件加载环境变量（如果存在）。
# .env 不会被提交到 git（见 .gitignore），真正的 API Key 只放在本地。
load_dotenv()


class Settings:
    # ------------------------------------------------------------------
    # LLM 相关配置
    # ------------------------------------------------------------------
    # 使用 Gemini（题目里"另外提供的真实可调用 LLM API Key"）。
    # 之所以做成可插拔（见 llm_client.py），是因为：
    #   1) 沙箱/答辩环境不一定能访问 Gemini 的域名，需要能一键切换成 Mock；
    #   2) 万一现场发的 Key 换成了别的厂商，只需要新增一个 Client 实现类。
    GEMINI_API_KEY: str = os.getenv("GEMINI_API_KEY", "")
    GEMINI_MODEL: str = os.getenv("GEMINI_MODEL", "gemini-2.0-flash")

    # LLM_PROVIDER = "gemini" | "mock"
    # 本地没有网络 / 没配 Key 时自动降级为 mock，方便先把架构跑通。
    LLM_PROVIDER: str = os.getenv("LLM_PROVIDER", "gemini" if GEMINI_API_KEY else "mock")

    # ------------------------------------------------------------------
    # 安全约束相关配置（对应笔试题"硬性约束" 1~4）
    # ------------------------------------------------------------------
    # 约束 1：任意 60 秒滑动窗口内，同一客户最多收到 1 条主动消息。
    RATE_LIMIT_WINDOW_SECONDS: int = int(os.getenv("RATE_LIMIT_WINDOW_SECONDS", "60"))
    RATE_LIMIT_MAX_MESSAGES: int = int(os.getenv("RATE_LIMIT_MAX_MESSAGES", "1"))

    # 约束 2：连续 N 次"答非所问 / 情绪不满"触发转人工。
    # 笔试原文是"连续两次"，这里做成可配置，方便测试时改成 1 次快速验证状态机。
    ESCALATE_AFTER_CONSECUTIVE_BAD: int = int(os.getenv("ESCALATE_AFTER_CONSECUTIVE_BAD", "2"))

    # ------------------------------------------------------------------
    # 多次调用 · 复盘机制（判断一条客户消息的意图/情绪时，不只调用一次 LLM）
    # ------------------------------------------------------------------
    # 每条消息独立调用 N 次分类，多数一致才直接采用；
    # N 次结果没有多数意见（比如3次给出3个不同的intent）时，
    # 触发一次"复盘仲裁"调用，把分歧摊开给模型看，让它重新审视裁定最终结果。
    # 好处：
    #   1) 抗偶发误判——单次调用的随机性被多数投票平滑掉；
    #   2) 抗注入更稳——攻击者要在3次独立调用里都稳定得手，比在1次里侥幸得手难得多。
    # 用奇数（默认3），避免频繁出现平局。
    MULTI_CALL_VOTES: int = int(os.getenv("MULTI_CALL_VOTES", "3"))

    # ------------------------------------------------------------------
    # 服务相关
    # ------------------------------------------------------------------
    HOST: str = os.getenv("HOST", "0.0.0.0")
    PORT: int = int(os.getenv("PORT", "8000"))


settings = Settings()
